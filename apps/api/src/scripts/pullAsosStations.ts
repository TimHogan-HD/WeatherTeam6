/**
 * Regenerates `src/lib/weather/asosStations.ts`: every US ASOS station IEM
 * lists as online with an hourly rain gauge, as `[id, lat, lon, tz]`, for
 * `nearestGauge` to pick a trip crag's gauge from.
 *
 *   npm run gauges:pull --workspace=apps/api
 *
 * A snapshot, not a live lookup: IEM serves stations per state network, so a
 * live nearest-station search would be fifty requests. Stations come and go
 * slowly; rerun it a few times a year.
 *
 * **Left out on purpose:** `STUCK_GAUGES` (`asosGauge.ts`), gauges measured
 * reading zero through real rain. They stay in the file so the exclusion is
 * one visible list rather than a silent gap in the snapshot.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { fetchWithRetry } from '../lib/weather/openMeteo.js'

// The fifty states, DC and Puerto Rico, as IEM names their ASOS networks.
const STATES = (
  'AK AL AR AZ CA CO CT DC DE FL GA HI IA ID IL IN KS KY LA MA MD ME MI MN MO MS MT NC ND NE NH NJ NM NV NY ' +
  'OH OK OR PA PR RI SC SD TN TX UT VA VT WA WI WV WY'
).split(' ')

type Feature = {
  id: string
  properties: {
    online?: boolean
    archive_end?: string | null
    tzname?: string | null
    attributes?: { HAS_PHOUR?: string }
  }
  geometry: { coordinates: [number, number] } | null
}

type StationRow = [id: string, lat: number, lon: number, tz: string]

async function network(state: string): Promise<StationRow[]> {
  const res = await fetchWithRetry(`https://mesonet.agron.iastate.edu/geojson/network/${state}_ASOS.geojson`)
  if (!res.ok) throw new Error(`${res.status} for ${state}_ASOS`)
  const body = (await res.json()) as { features: Feature[] }
  return body.features.flatMap((f): StationRow[] => {
    const p = f.properties
    const c = f.geometry?.coordinates
    // A station that has stopped reporting, or reports no hourly rain, can only ever be a gap.
    if (p.online !== true || p.archive_end != null || p.attributes?.HAS_PHOUR !== '1') return []
    if (c === undefined || typeof p.tzname !== 'string') return []
    const round = (v: number) => Math.round(v * 10_000) / 10_000
    return [[f.id, round(c[1]), round(c[0]), p.tzname]]
  })
}

async function main() {
  const rows: StationRow[] = []
  for (const state of STATES) {
    const got = await network(state)
    console.log(`${state}_ASOS  ${got.length}`)
    rows.push(...got)
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]))
  const out = fileURLToPath(new URL('../lib/weather/asosStations.ts', import.meta.url))
  writeFileSync(
    out,
    '// Generated by `npm run gauges:pull` (src/scripts/pullAsosStations.ts). Do not edit by hand.\n' +
      'export const ASOS_STATIONS: readonly [id: string, lat: number, lon: number, tz: string][] = [\n' +
      rows.map((r) => `  ${JSON.stringify(r)},`).join('\n') +
      '\n]\n',
  )
  console.log(`${rows.length} stations → ${out}`)
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
