/**
 * Regenerates `src/lib/weather/cocorahsStations.ts`: every US CoCoRaHS
 * volunteer gauge that reported on at least one of `SAMPLE_DAYS_BACK`, as
 * `[id, lat, lon]`, for `nearestVolunteerGauges` to pick a trip crag's
 * gauges from.
 *
 *   npm run volunteer-gauges:pull --workspace=apps/api
 *
 * **Picked by reports, not by listing.** IEM lists about five times as many
 * stations as report on a given day (6,006 in Minnesota, about 1,050 reporting
 * on 2026-11-01); a listed station that never reports is a permanent gap that
 * would sit nearer a crag than one that does. Volunteers come and go, so rerun
 * it a few times a year.
 *
 * Coordinates are cut to three decimals (about 100 m) and names are left out,
 * to keep about 15,000 stations small; the recorder stores each report's name
 * from the report itself.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { fetchWithRetry } from '../lib/weather/openMeteo.js'

// The fifty states, DC and Puerto Rico, as IEM names their CoCoRaHS networks.
const STATES = (
  'AK AL AR AZ CA CO CT DC DE FL GA HI IA ID IL IN KS KY LA MA MD ME MI MN MO MS MT NC ND NE NH NJ NM NV NY ' +
  'OH OK OR PA PR RI SC SD TN TX UT VA VT WA WI WV WY'
).split(' ')

/** Days before today whose reports qualify a station: three weeks, so a volunteer away for one still counts. */
const SAMPLE_DAYS_BACK = [3, 10, 17]

type Feature = {
  id: string
  properties: { online?: boolean; archive_end?: string | null }
  geometry: { coordinates: [number, number] } | null
}

type StationRow = [id: string, lat: number, lon: number]

async function json<T>(url: string): Promise<T> {
  const res = await fetchWithRetry(url)
  if (!res.ok) throw new Error(`${res.status} for ${url}`)
  return (await res.json()) as T
}

async function reportedOn(state: string, date: string): Promise<Set<string>> {
  const body = await json<{ data: { station: string; precip: number | null }[] }>(
    `https://mesonet.agron.iastate.edu/api/1/daily.json?network=${state}_COCORAHS&date=${date}`,
  )
  return new Set(body.data.filter((r) => r.precip !== null).map((r) => r.station))
}

async function network(state: string, dates: string[]): Promise<StationRow[]> {
  const reported = new Set<string>()
  for (const date of dates) for (const id of await reportedOn(state, date)) reported.add(id)
  const listed = await json<{ features: Feature[] }>(
    `https://mesonet.agron.iastate.edu/geojson/network/${state}_COCORAHS.geojson`,
  )
  return listed.features.flatMap((f): StationRow[] => {
    const c = f.geometry?.coordinates
    if (!reported.has(f.id) || c === undefined) return []
    const round = (v: number) => Math.round(v * 1000) / 1000
    return [[f.id, round(c[1]), round(c[0])]]
  })
}

async function main() {
  const now = Date.now()
  const dates = SAMPLE_DAYS_BACK.map((d) => new Date(now - d * 86_400_000).toISOString().slice(0, 10))
  const rows: StationRow[] = []
  for (const state of STATES) {
    const got = await network(state, dates)
    console.log(`${state}_COCORAHS  ${got.length}`)
    rows.push(...got)
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]))
  const out = fileURLToPath(new URL('../lib/weather/cocorahsStations.ts', import.meta.url))
  writeFileSync(
    out,
    '// Generated by `npm run volunteer-gauges:pull` (src/scripts/pullCocorahsStations.ts). Do not edit by hand.\n' +
      `// Stations that reported on ${dates.join(', ')}.\n` +
      'export const COCORAHS_STATIONS: readonly [id: string, lat: number, lon: number][] = [\n' +
      rows.map((r) => `  ${JSON.stringify(r)},`).join('\n') +
      '\n]\n',
  )
  console.log(`${rows.length} stations → ${out}`)
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
